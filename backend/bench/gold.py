@dataclass(frozen=True)
class GoldStep:
    name: str
    source: str
    target: str
    func: Callable[..., dict]
    estimate: Callable[[str, str, dict], tuple[int, int]]


GOLD_STEPS = (
    GoldStep("correction", "initial.md", "corrected.md", steps.correction, steps.estimate_correction),
    GoldStep("edition", "corrected.md", "edited.md", steps.edition, steps.estimate_edition),
    GoldStep("edited_ideas", "corrected.md", "edited_ideas.yaml", edited_ideas,
             _estimate_structured(IDEAS_OUTPUT_INSTRUCTIONS)),
    GoldStep("summary", "edited.md", "summary.md", steps.summary, steps.estimate_summary),
    GoldStep("summary_keypoints", "edited.md", "summary_keypoints.yaml", summary_keypoints,
             _estimate_structured(KEYPOINTS_OUTPUT_INSTRUCTIONS)),
)
# Closest earlier file to estimate a step whose input is generated in the same run.
PROXY_FILES = {"edited.md": "corrected.md", "corrected.md": "initial.md"}

DEFAULT_TIMEOUT_S = 600
DEFAULT_RETRIES = 2


def dataset_files(kind: str) -> set[str]:
    """Files used by the dataset `kind` (empty for a dataset other than extracts and full)."""
    return set(REQUIRED_FILES.get(kind, ())) | set(OPTIONAL_FILES.get(kind, ()))


def resolve_path(value: str) -> Path:
    path = Path(value)
    if path.is_absolute() or path.exists():
        return path
    return BENCH_DIR / path


def load_lessons(config: dict, only: Optional[list[str]]) -> tuple[list[LessonItem], list[str]]:
    """Lessons of `dataset:` (in order, kind = dataset name), filtered by folder name. (lessons, problems)."""
    dataset = config.get("dataset")
    if not isinstance(dataset, dict) or not dataset:
        return [], ["'dataset' must map a dataset (extracts, full) to a list of lesson folders"]
    lessons, problems = [], []
    for kind, paths in dataset.items():
        if not isinstance(paths, list):
            problems.append(f"dataset.{kind}: must be a list of lesson folders")
            continue
        if kind not in REQUIRED_FILES:
            print(f"WARNING dataset.{kind}: unknown dataset (known: {', '.join(REQUIRED_FILES)}), all steps allowed")
        for value in paths:
            path = resolve_path(str(value))
            if not path.is_dir():
                print(f"WARNING dataset.{kind}: lesson folder not found, skipped: {value}")
            elif not only or path.name in only:
                lessons.append(LessonItem(id=path.name, kind=kind, path=path))
    if only:
        unknown = set(only) - {l.id for l in lessons}
        if unknown:
            problems.append(f"--lessons: not in the dataset: {', '.join(sorted(unknown))}")
    return lessons, problems


def check_config(config: dict, selected: list[GoldStep]) -> list[str]:
    problems = []
    for step in selected:
        spec = config.get(step.name)
        if not isinstance(spec, dict):
            problems.append(f"{step.name}: missing in the config")
            continue
        prompt = spec.get("prompt")
        if not prompt or not resolve_path(str(prompt)).is_file():
            problems.append(f"{step.name}: prompt file not found: {prompt}")
        model = spec.get("model")
        if not isinstance(model, dict) or not model.get("id"):
            problems.append(f"{step.name}: 'model' must be a mapping with id, provider and params")
            continue
        if str(model.get("provider", "")).lower() not in steps.PROVIDERS:
            problems.append(f"{step.name}: 'provider' must be one of {list(steps.PROVIDERS)}, got {model.get('provider')!r}")
        for key, value in (("model.params", model.get("params")), ("params", spec.get("params"))):
            if value is not None and not isinstance(value, dict):
                problems.append(f"{step.name}: '{key}' must be a mapping")
    return problems


def step_params(spec: dict) -> dict:
    return {**(spec["model"].get("params") or {}), **(spec.get("params") or {})}


def read_prompt(spec: dict) -> str:
    return resolve_path(str(spec["prompt"])).read_text(encoding="utf-8-sig")


def flex_for(spec: dict, pricing: Pricing, flex: bool) -> bool:
    """--flex applies to the step when its model has a flex tier (OpenRouter + flex ratio)."""
    return flex and pricing.flex_available(spec["model"]["id"], spec["model"].get("provider"))


def call_with_retries(step: GoldStep, text: str, item: LessonItem, spec: dict, timeout: float,
                      retries: int, flex: bool = False) -> tuple[dict, int]:
    """(adapter result, attempts). Raises the last error."""
    model = spec["model"]
    params = {**step_params(spec), **({"use_flex": True} if flex else {})}
    prompt = read_prompt(spec)
    for attempt in range(retries + 1):
        try:
            result = step.func(text, item=item, provider=model["provider"], model=model["id"], prompt=prompt,
                               params=dict(params), timeout=timeout)
            return result, attempt + 1
        except Exception as exc:
            if not getattr(exc, "retryable", True) or attempt == retries:
                raise
            print(f"    attempt {attempt + 1} failed ({type(exc).__name__}: {exc}), retrying")
            time.sleep(RETRY_DELAY_S * 2**attempt)
    raise AssertionError("unreachable")


def output_text(output) -> str:
    text = output if isinstance(output, str) else yaml.safe_dump(output, allow_unicode=True, sort_keys=False)
    return text if text.endswith("\n") else text + "\n"


def write_file(path: Path, text: str) -> None:
    """Write through a temporary file, so an interrupted run never leaves a partial gold file."""
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def sanity_warnings(step: GoldStep, source: str, output: str) -> list[str]:
    if step.name != "correction":
        return []
    before, _ = parse_transcript(source)
    after, problems = parse_transcript(output)
    warnings = []
    if problems:
        warnings.append(f"{len(problems)} line(s) of the output are not `- [start - end] text` lines")
    if [(s.start, s.end) for s in before] != [(s.start, s.end) for s in after]:
        warnings.append(f"segments differ from initial.md ({len(before)} -> {len(after)})")
    return warnings


# --------------------------------------------------------------------------- #
# Plan and cost estimate
# --------------------------------------------------------------------------- #

RUN, EXISTS, UNUSED, NO_INPUT = "run", "exists", "unused", "no input"


@dataclass
class Task:
    item: LessonItem
    step: GoldStep
    status: str
    chained: bool = False                # input generated by an earlier step of the run
    flex: bool = False                   # OpenRouter flex tier (--flex)
    est_tokens_in: int = 0
    est_tokens_out: int = 0
    est_cost: Optional[float] = None     # None: no price in pricing.yaml


def plan(lessons: list[LessonItem], selected: list[GoldStep], step_specs: dict, pricing: Pricing,
         flex: bool = False) -> list[Task]:
    tasks = []
    for item in lessons:
        files = dataset_files(item.kind)
        generated: set[str] = set()
        for step in selected:
            source_path = item.path / step.source
            if files and step.target not in files:
                tasks.append(Task(item, step, UNUSED))
            elif (item.path / step.target).exists():
                tasks.append(Task(item, step, EXISTS))
            elif source_path.is_file() or step.source in generated:
                task = Task(item, step, RUN, chained=not source_path.is_file(),
                            flex=flex_for(step_specs[step.name], pricing, flex))
                estimate(task, step_specs[step.name], pricing)
                tasks.append(task)
                generated.add(step.target)
            else:
                tasks.append(Task(item, step, NO_INPUT))
    return tasks


def estimate(task: Task, spec: dict, pricing: Pricing) -> None:
    """Tokens and cost of a task; a chained input is approximated by the closest existing file."""
    name = task.step.source
    while not (task.item.path / name).is_file() and name in PROXY_FILES:
        name = PROXY_FILES[name]
    path = task.item.path / name
    text = path.read_text(encoding="utf-8-sig") if path.is_file() else ""
    task.est_tokens_in, task.est_tokens_out = task.step.estimate(text, read_prompt(spec), step_params(spec))
    price = pricing.price(spec["model"]["id"], spec["model"].get("provider"), flex=task.flex)
    task.est_cost = compute_cost(price, task.est_tokens_in, task.est_tokens_out) if price else None


def print_plan(tasks: list[Task], lessons: list[LessonItem], selected: list[GoldStep], step_specs: dict,
               flex: bool = False) -> float:
    """Status matrix (lesson x step), then calls and estimated cost per step. Returns the estimated cost."""
    marks = {RUN: "RUN", EXISTS: "exists", UNUSED: "-", NO_INPUT: "no input"}
    by_key = {(t.item.path, t.step.name): t for t in tasks}
    width = max([len(l.id) for l in lessons] + [6])
    widths = [max(len(s.name), 8) for s in selected]
    header = f"{'lesson':{width}}  " + "  ".join(f"{s.name:{w}}" for s, w in zip(selected, widths))
    print(header)
    print("-" * len(header))
    for item in lessons:
        cells = []
        for step, w in zip(selected, widths):
            task = by_key[(item.path, step.name)]
            cells.append(f"{marks[task.status] + ('*' if task.chained else ''):{w}}")
        print(f"{item.id:{width}}  " + "  ".join(cells))
    print("RUN = generated, exists = kept, - = not used by the dataset, no input = input file missing")

    todo = [t for t in tasks if t.status == RUN]
    if not todo:
        return 0.0
    print()
    header = f"{'step':17} {'model':40} {'calls':>5} {'est. tokens in/out':>20} {'est. USD':>9}"
    print(header)
    print("-" * len(header))
    total, unknown = 0.0, False
    for step in selected:
        group = [t for t in todo if t.step.name == step.name]
        if not group:
            continue
        model = step_specs[step.name]["model"]["id"] + (" (flex)" if group[0].flex else "")
        tokens = f"{sum(t.est_tokens_in for t in group):,}/{sum(t.est_tokens_out for t in group):,}"
        if any(t.est_cost is None for t in group):
            unknown, cost_text = True, "?"
        else:
            cost = sum(t.est_cost for t in group)
            total += cost
            cost_text = f"{cost:.4f}"
        print(f"{step.name:17} {model[:40]:40} {len(group):>5} {tokens:>20} {cost_text:>9}")
    print("-" * len(header))
    print(f"{len(todo)} calls -- estimated cost ${total:.4f}" + (" + unknown (? = no price in configs/pricing.yaml)" if unknown else ""))
    if any(t.chained for t in todo):
        print("* input generated by an earlier step of this run: estimated from the closest existing file")
    print("Estimates use ~3.5 characters/token and do not include reasoning tokens.")
    print_flex(flex, {step_specs[t.step.name]["model"]["id"]: t.flex for t in todo})
    return total


