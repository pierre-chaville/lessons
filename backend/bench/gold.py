# --------------------------------------------------------------------------- #
# Ideas (structured output)
# --------------------------------------------------------------------------- #

IDEAS_OUTPUT_INSTRUCTIONS = (
    "Pour chaque idée, donne : `text` (l'idée en une phrase), `elements` (les 2 à 4 éléments "
    "essentiels de l'idée, chacun en quelques mots : ce qui doit être dit pour que l'idée soit "
    "présente dans une version éditée), `importance` (high, medium ou low) et `timestamp` (le début "
    "du segment de la transcription où l'idée est enseignée, recopié tel quel, par exemple `4m 04s`). "
    "Liste les idées dans l'ordre du cours."
)


class Idea(BaseModel):
    text: str = Field(description="L'idée, en une phrase autonome.")
    elements: list[str] = Field(description="Les 2 à 4 éléments essentiels de l'idée, chacun en quelques mots.")
    importance: Literal["high", "medium", "low"] = Field(description="high, medium ou low.")
    timestamp: str = Field(description="Début du segment où l'idée est enseignée, ex. `4m 04s`.")


class IdeaList(BaseModel):
    ideas: list[Idea]


def _snap_timestamp(value: str, segments: list[Segment]) -> tuple[str, bool]:
    """Timestamp of the model -> start of the segment that contains it. (timestamp, valid)."""
    seconds = parse_duration(value.strip().strip("[]`"))
    if seconds is None or not segments:
        return value, False
    containing = [s for s in segments if s.start <= seconds <= s.end]
    if containing:
        return _format_seconds(containing[0].start), True
    nearest = min(segments, key=lambda s: abs(s.start - seconds))
    return _format_seconds(nearest.start), abs(nearest.start - seconds) <= 5


def points_yaml(points: list[dict]) -> str:
    """Same layout as the hand-made files: one block per entry, separated by a blank line."""
    return "\n".join(
        yaml.safe_dump([p], allow_unicode=True, sort_keys=False, width=10**6) for p in points
    )


_STRUCTURED_PARAMS = {"structured_output_method"}


structured_call = steps.structured_call


STRUCTURED_OUTPUT_TOKENS = 2000  # estimate of a list of ideas / key points


def _estimate_structured(instructions: str):
    def estimate(text: str, prompt: str, params: dict) -> tuple[int, int]:
        tokens_in = steps.approx_tokens(prompt) + steps.approx_tokens(instructions) + steps.approx_tokens(text) + 10
        return tokens_in, min(int(params.get("max_tokens") or 10**9), STRUCTURED_OUTPUT_TOKENS)

    return estimate


def edited_ideas(text: str, *, item: Any, provider: str, model: str, prompt: str, params: dict,
                 timeout: float) -> dict:
    """Ideas of an extract (corrected.md -> edited_ideas.yaml), with structured output.

    Each idea gets an id (1, 2, ...), its importance and the start of the segment where it is
    taught (a timestamp of the model that is not in the transcript is snapped to the segment
    containing it).
    """
    steps._check_params(params, _STRUCTURED_PARAMS)
    segments = steps._parse_input_transcript(text)
    full_prompt = f"{prompt}\n\n{IDEAS_OUTPUT_INSTRUCTIONS}\n\nTranscription :\n{text}"
    parsed, tokens = structured_call(IdeaList, full_prompt, provider=provider, model=model, params=params,
                                     timeout=timeout)
    if not parsed.ideas:
        raise steps.StepError("no idea in the output", **tokens)

    points, invalid = [], []
    for index, idea in enumerate(parsed.ideas, start=1):
        timestamp, valid = _snap_timestamp(idea.timestamp, segments)
        if not valid:
            invalid.append(f"id {index}: {idea.timestamp!r}")
        elements = [e.strip() for e in idea.elements if e.strip()]
        points.append({"id": index, "text": idea.text.strip(), **({"elements": elements} if elements else {}),
                       "importance": idea.importance, "timestamp": timestamp})
    return {
        "output": points_yaml(points),
        **tokens,
        "cost_usd": None,
        "meta": {"ideas": len(points), "invalid_references": invalid},
    }


# --------------------------------------------------------------------------- #
# Summary key points (structured output)
# --------------------------------------------------------------------------- #

KEYPOINTS_OUTPUT_INSTRUCTIONS = (
    "La version rédigée est donnée paragraphe par paragraphe, au format `<numéro> | <texte>`. "
    "Pour chaque point clé, donne : `text` (le point en une phrase), `importance` (high, medium "
    "ou low), `paragraph_start` et `paragraph_end` (numéros du premier et du dernier paragraphe "
    "où le point est principalement développé ; le même numéro si un seul paragraphe)."
)


class KeyPoint(BaseModel):
    text: str = Field(description="Le point clé, en une phrase autonome.")
    importance: Literal["high", "medium", "low"] = Field(description="high, medium ou low.")
    paragraph_start: int = Field(description="Numéro du premier paragraphe où le point est développé.")
    paragraph_end: int = Field(description="Numéro du dernier paragraphe où le point est développé.")


class KeyPointList(BaseModel):
    keypoints: list[KeyPoint]


def numbered_paragraphs(markdown: str) -> tuple[str, int]:
    """(`<id> | <text>` lines, number of paragraphs): empty paragraphs removed, numbered from 1."""
    items = paragraphs(markdown)
    return "\n".join(f"{i} | {p}" for i, p in enumerate(items, start=1)), len(items)


def summary_keypoints(text: str, *, item: Any, provider: str, model: str, prompt: str, params: dict,
                      timeout: float) -> dict:
    """Key points of a full lesson (edited.md -> summary_keypoints.yaml), with structured output.

    The edited version is sent as numbered paragraphs (`<id> | <text>`); each key point gets an id
    (1, 2, ...), its importance and the range of paragraphs where it is developed (numbers of
    `dataset.paragraphs`). Out-of-range or reversed ranges are fixed and reported.
    """
    steps._check_params(params, _STRUCTURED_PARAMS)
    numbered, count = numbered_paragraphs(text)
    if not count:
        raise steps.StepError("input is empty", retryable=False)
    full_prompt = f"{prompt}\n\n{KEYPOINTS_OUTPUT_INSTRUCTIONS}\n\nVersion rédigée :\n{numbered}"
    parsed, tokens = structured_call(KeyPointList, full_prompt, provider=provider, model=model, params=params,
                                     timeout=timeout)
    if not parsed.keypoints:
        raise steps.StepError("no key point in the output", **tokens)

    points, invalid = [], []
    for index, point in enumerate(parsed.keypoints, start=1):
        start, end = point.paragraph_start, point.paragraph_end
        fixed_start, fixed_end = sorted((min(max(start, 1), count), min(max(end, 1), count)))
        if (fixed_start, fixed_end) != (start, end):
            invalid.append(f"id {index}: {start}-{end} -> {fixed_start}-{fixed_end}")
        points.append({
            "id": index, "text": point.text.strip(), "importance": point.importance,
            "paragraph_start": fixed_start, "paragraph_end": fixed_end,
        })
    return {
        "output": points_yaml(points),
        **tokens,
        "cost_usd": None,
        "meta": {"keypoints": len(points), "paragraphs": count, "invalid_references": invalid},
    }


