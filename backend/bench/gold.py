def run(tasks: list[Task], step_specs: dict, pricing: Pricing, timeout: float, retries: int) -> int:
    failed = generated = 0
    total_cost = 0.0
    current = None
    for task in tasks:
        if task.status != RUN:
            continue
        item, step = task.item, task.step
        if item.path != current:
            current = item.path
            print(f"\n== {item.kind}/{item.id}")
        source_path, target_path = item.path / step.source, item.path / step.target
        label = f"{step.name:17} {step.source} -> {step.target}"
        if target_path.exists():
            print(f"{label}: exists, skipped")
            continue
        if not source_path.is_file():
            print(f"{label}: SKIPPED, {step.source} not found (previous step failed)")
            continue
        spec = step_specs[step.name]
        model = spec["model"]
        print(f"{label}: generating with {model['id']} ({model['provider']}{', flex' if task.flex else ''})...")
        source = source_path.read_text(encoding="utf-8-sig")
        started = time.perf_counter()
        try:
            result, attempts = call_with_retries(step, source, item, spec, timeout, retries, flex=task.flex)
        except Exception as exc:
            failed += 1
            print(f"    FAILED: {type(exc).__name__}: {exc}")
            continue
        text = output_text(result["output"])
        write_file(target_path, text)
        generated += 1

        tokens_in, tokens_out = int(result.get("tokens_in") or 0), int(result.get("tokens_out") or 0)
        price = pricing.price(model["id"], model.get("provider"), flex=task.flex)
        cost = result.get("cost_usd")
        if cost is None and price is not None:
            cost = compute_cost(price, tokens_in, tokens_out)
        total_cost += cost or 0.0
        cost_text = f"${cost:.4f}" if cost is not None else "cost unknown (no price in configs/pricing.yaml)"
        print(f"    written: {target_path}  ({time.perf_counter() - started:.0f}s, {attempts} attempt(s), "
              f"{tokens_in:,}/{tokens_out:,} tokens, {cost_text})")
        for warning in sanity_warnings(step, source, text):
            print(f"    WARNING: {warning}")
        meta = result.get("meta") or {}
        if "new_glossary_entries" in meta:
            entries = meta["new_glossary_entries"]
            task_id = meta.get("glossary_completion_task")
            print(f"    glossary: {len(entries)} new entr{'y' if len(entries) == 1 else 'ies'}"
                  + (f": {', '.join(entries)}" if entries else "")
                  + (f" (completion task {task_id})" if task_id else ""))
        invalid = meta.get("invalid_references")
        if invalid:
            print(f"    WARNING: timestamps / paragraphs not found in the input (check them): {', '.join(invalid)}")

    print(f"\n{generated} file(s) generated, {failed} failed -- cost ${total_cost:.4f}")
    if generated:
        print("Review the generated files by hand, then validate the lessons with: python -m bench.run <campaign> --check")
    return 1 if failed else 0


def main(argv: Optional[list[str]] = None) -> int:
    names = [s.name for s in GOLD_STEPS]
    parser = argparse.ArgumentParser(description="Draft the gold files of the lessons of a config with an LLM.")
    parser.add_argument("--config", required=True, help="gold config, e.g. configs/gold_v1.yaml")
    parser.add_argument("--steps", nargs="+", choices=names, help="subset of the steps of the config (default: all of them)")
    parser.add_argument("--lessons", nargs="+", metavar="NAME", help="subset of the lessons (folder names)")
    parser.add_argument("--dry-run", action="store_true", help="show the plan and the estimated cost only")
    parser.add_argument("--yes", "-y", action="store_true", help="do not ask for confirmation")
    parser.add_argument("--flex", action="store_true",
                        help="OpenRouter flex tier for the models with a flex ratio in configs/pricing.yaml")
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_S, help="timeout of each LLM call (s)")
    parser.add_argument("--retries", type=int, default=DEFAULT_RETRIES, help="retries of a failed step")
    parser.add_argument("--verbose", action="store_true", help="show the logs of the app code")
    args = parser.parse_args(argv)

    sys.stdout.reconfigure(line_buffering=True)
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    if not args.verbose:
        logging.getLogger("services").setLevel(logging.CRITICAL)

    config_path = resolve_path(args.config)
    if not config_path.is_file():
        print(f"config not found: {args.config}")
        return 2
    config = yaml.safe_load(config_path.read_text(encoding="utf-8-sig")) or {}
    print(f"Config: {config_path}\n")
    step_specs = config.get("steps")
    lessons, problems = load_lessons(config, args.lessons)
    if not isinstance(step_specs, dict):
        problems.append("'steps' must map each step to its prompt and model")
    if not lessons:
        problems.append("no lesson to process")
    if problems:
        for problem in problems:
            print(f"ERROR {problem}")
        return 2

    unknown = set(step_specs) - set(names)
    if unknown:
        print(f"ERROR steps: unknown step(s) {', '.join(sorted(unknown))} (known: {', '.join(names)})")
        return 2
    not_configured = set(args.steps or ()) - set(step_specs)
    if not_configured:
        print(f"ERROR --steps: not in the config: {', '.join(sorted(not_configured))}")
        return 2
    selected = [s for s in GOLD_STEPS if s.name in step_specs and (not args.steps or s.name in args.steps)]
    used = {s.name for item in lessons for s in selected
            if not dataset_files(item.kind) or s.target in dataset_files(item.kind)}
    problems = check_config(step_specs, [s for s in selected if s.name in used])
    if problems:
        for problem in problems:
            print(f"ERROR {problem}")
        return 2

    pricing = load_pricing()
    tasks = plan(lessons, selected, step_specs, pricing, flex=args.flex)
    print_plan(tasks, lessons, selected, step_specs, flex=args.flex)
    n_todo = sum(1 for t in tasks if t.status == RUN)
    if not n_todo:
        print("\nNothing to generate.")
        return 0
    if args.dry_run:
        return 0
    if not args.yes and not confirm(f"\nRun {n_todo} calls?"):
        print("Aborted.")
        return 1
    return run(tasks, step_specs, pricing, args.timeout, args.retries)


if __name__ == "__main__":
    sys.exit(main())
