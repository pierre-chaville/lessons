"""Draft the gold files of the lessons of a config with an LLM, to be reviewed by hand afterwards.

Usage (from backend/):
    python -m bench.gold --config configs/gold_v1.yaml                  # plan, cost, confirm, run
    python -m bench.gold --config configs/gold_v1.yaml --dry-run        # plan and cost only
    python -m bench.gold --config configs/gold_v1.yaml --steps summary --lessons Parashah.Bo

Only the steps of `steps:` in the config are run (e.g. correction only, to review corrected.md
before the next steps), in this order for each lesson (correction, edition and summary through the same
adapters as the bench, bench/steps.py; edited_ideas and summary_keypoints with a structured output):
    correction:        initial.md   -> corrected.md
    edition:           corrected.md -> edited.md
    edited_ideas:      corrected.md -> edited_ideas.yaml
    summary:           edited.md    -> summary.md
    summary_keypoints: edited.md    -> summary_keypoints.yaml

Only the files used by the dataset of the lesson are generated (`extracts`: corrected.md,
edited.md, edited_ideas.yaml; `full`: corrected.md, edited.md, summary.md, summary_keypoints.yaml).
An existing output file is never overwritten: its step is skipped (delete the file to regenerate
it). A step whose input is missing is skipped too; a file generated by a step is the input of the
next one (its cost is then estimated from the closest existing file). Paths are relative to the
current folder or to bench/.

Config (`params` = model params + step params, as in the campaigns):
    dataset:
      extracts: [data/extracts/<lesson_id>, ...]
      full: [data/full/<lesson_id>, ...]
    steps:
      correction:
        prompt: prompts/correction/standard_V1.md
        model: { id: openai/gpt-6-luna, provider: openrouter, params: { temperature: 1.0 } }
        params: { segments_per_group: 10 }      # optional
        # params: { extract_glossary: true }    # add the new Hebrew terms to the app glossary
                                                # (as the app correction in native Hebrew mode)
"""

