"""Draft the gold files of a lesson with an LLM, to be reviewed by hand afterwards.

Usage (from backend/):
    python -m bench.gold data/extracts/<lesson_id> --config configs/gold_v1.yaml
    python -m bench.gold data/full/<lesson_id> --config configs/gold_v1.yaml --steps summary

Steps, run in this order (correction, edition and summary through the same adapters as the
bench, bench/steps.py; edited_ideas and summary_keypoints with a structured output):
    correction:        initial.md   -> corrected.md
    edition:           corrected.md -> edited.md
    edited_ideas:      corrected.md -> edited_ideas.yaml
    summary:           edited.md    -> summary.md
    summary_keypoints: edited.md    -> summary_keypoints.yaml

Only the files used by the dataset of the lesson are generated (parent folder `extracts`:
corrected.md, edited.md, edited_ideas.yaml; `full`: corrected.md, edited.md, summary.md,
summary_keypoints.yaml). An existing output file is never overwritten:
its step is skipped (delete the file to regenerate it). A step whose input is missing is skipped
too; a file generated by a step is the input of the next one. Paths are relative to the current
folder or to bench/.

Config (one entry per step; `params` = model params + step params, as in the campaigns):
    correction:
      prompt: prompts/correction/standard_V1.md
      model: { id: openai/gpt-6-luna, provider: openrouter, params: { temperature: 1.0 } }
      params: { segments_per_group: 10 }      # optional
"""

from __future__ import annotations

import argparse
import asyncio
import logging
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Literal, Optional

import yaml
from pydantic import BaseModel, Field

from bench import steps
from bench.dataset import (
    BENCH_DIR, OPTIONAL_FILES, REQUIRED_FILES, LessonItem, Segment, _format_seconds, paragraphs,
    parse_duration, parse_transcript,
)
from bench.run import RETRY_DELAY_S, compute_cost, load_pricing


# --------------------------------------------------------------------------- #
# Ideas (structured output)
# --------------------------------------------------------------------------- #

IDEAS_OUTPUT_INSTRUCTIONS = (
    "Pour chaque idée, donne : `text` (l'idée en une phrase), `importance` (high, medium ou low) "
    "et `timestamp` (le début du segment de la transcription où l'idée est enseignée, recopié tel "
    "quel, par exemple `4m 04s`). Liste les idées dans l'ordre du cours."
)


class Idea(BaseModel):
    text: str = Field(description="L'idée, en une phrase autonome.")
    importance: Literal["high", "medium", "low"] = Field(description="high, medium ou low.")
    timestamp: str = Field(description="Début du segment où l'idée est enseignée, ex. `4m 04s`.")


class IdeaList(BaseModel):
    ideas: list[Idea]


def _snap_timestamp(value: str, segments: list[Segment]) -> tuple[str, bool]:
    """Timestamp of the model -> start of the segment that contains it. (timestamp, valid)."""
    seconds = parse_duration(value.strip().strip("[]`"))
    if seconds is None or not segments:
        return value, False
    containing = [s for s in segments if s.start <= seconds <= s.end]
    if containing:
        return _format_seconds(containing[0].start), True
    nearest = min(segments, key=lambda s: abs(s.start - seconds))
    return _format_seconds(nearest.start), abs(nearest.start - seconds) <= 5


def points_yaml(points: list[dict]) -> str:
    """Same layout as the hand-made files: one block per entry, separated by a blank line."""
    return "\n".join(
        yaml.safe_dump([p], allow_unicode=True, sort_keys=False, width=10**6) for p in points
    )


_STRUCTURED_PARAMS = {"structured_output_method"}


def structured_call(schema: type[BaseModel], full_prompt: str, *, provider: str, model: str, params: dict,
                    timeout: float) -> tuple[BaseModel, dict]:
    """One LLM call with a structured output (LangChain `with_structured_output`).
    Returns (parsed object, {"tokens_in", "tokens_out"}); raises StepError on failure.
    Step param `structured_output_method`: method of with_structured_output (default: the
    provider default, i.e. function calling)."""
    llm = steps._build_llm(provider, model, params, default_max_tokens=16000)
    method = params.get("structured_output_method")
    structured = llm.with_structured_output(schema, include_raw=True, **({"method": method} if method else {}))

    async def call():
        return await asyncio.wait_for(structured.ainvoke(full_prompt), timeout)

    try:
        response = asyncio.run(call())
    except asyncio.TimeoutError:
        raise steps.StepError(f"timeout after {timeout}s")
    raw = response.get("raw")
    usage = getattr(raw, "usage_metadata", None) or {}
    tokens = {"tokens_in": int(usage.get("input_tokens") or 0), "tokens_out": int(usage.get("output_tokens") or 0)}
    metadata = getattr(raw, "response_metadata", None) or {}
    if metadata.get("finish_reason") == "length" or metadata.get("stop_reason") == "max_tokens":
        raise steps.StepError("output truncated (max_tokens reached)", retryable=False, **tokens)
    parsed = response.get("parsed")
    if parsed is None:
        raise steps.StepError(f"invalid structured output: {response.get('parsing_error')}", **tokens)
    return parsed, tokens


def edited_ideas(text: str, *, item: Any, provider: str, model: str, prompt: str, params: dict,
                 timeout: float) -> dict:
    """Ideas of an extract (corrected.md -> edited_ideas.yaml), with structured output.

    Each idea gets an id (1, 2, ...), its importance and the start of the segment where it is
    taught (a timestamp of the model that is not in the transcript is snapped to the segment
    containing it).
    """
    steps._check_params(params, _STRUCTURED_PARAMS)
    segments = steps._parse_input_transcript(text)
    full_prompt = f"{prompt}\n\n{IDEAS_OUTPUT_INSTRUCTIONS}\n\nTranscription :\n{text}"
    parsed, tokens = structured_call(IdeaList, full_prompt, provider=provider, model=model, params=params,
                                     timeout=timeout)
    if not parsed.ideas:
        raise steps.StepError("no idea in the output", **tokens)

    points, invalid = [], []
    for index, idea in enumerate(parsed.ideas, start=1):
        timestamp, valid = _snap_timestamp(idea.timestamp, segments)
        if not valid:
            invalid.append(f"id {index}: {idea.timestamp!r}")
        points.append({"id": index, "text": idea.text.strip(), "importance": idea.importance, "timestamp": timestamp})
    return {
        "output": points_yaml(points),
        **tokens,
        "cost_usd": None,
        "meta": {"ideas": len(points), "invalid_references": invalid},
    }


# --------------------------------------------------------------------------- #
# Summary key points (structured output)
# --------------------------------------------------------------------------- #

KEYPOINTS_OUTPUT_INSTRUCTIONS = (
    "La version rédigée est donnée paragraphe par paragraphe, au format `<numéro> | <texte>`. "
    "Pour chaque point clé, donne : `text` (le point en une phrase), `importance` (high, medium "
    "ou low), `paragraph_start` et `paragraph_end` (numéros du premier et du dernier paragraphe "
    "où le point est principalement développé ; le même numéro si un seul paragraphe)."
)


class KeyPoint(BaseModel):
    text: str = Field(description="Le point clé, en une phrase autonome.")
    importance: Literal["high", "medium", "low"] = Field(description="high, medium ou low.")
    paragraph_start: int = Field(description="Numéro du premier paragraphe où le point est développé.")
    paragraph_end: int = Field(description="Numéro du dernier paragraphe où le point est développé.")


class KeyPointList(BaseModel):
    keypoints: list[KeyPoint]


def numbered_paragraphs(markdown: str) -> tuple[str, int]:
    """(`<id> | <text>` lines, number of paragraphs): empty paragraphs removed, numbered from 1."""
    items = paragraphs(markdown)
    return "\n".join(f"{i} | {p}" for i, p in enumerate(items, start=1)), len(items)


def summary_keypoints(text: str, *, item: Any, provider: str, model: str, prompt: str, params: dict,
                      timeout: float) -> dict:
    """Key points of a full lesson (edited.md -> summary_keypoints.yaml), with structured output.

    The edited version is sent as numbered paragraphs (`<id> | <text>`); each key point gets an id
    (1, 2, ...), its importance and the range of paragraphs where it is developed (numbers of
    `dataset.paragraphs`). Out-of-range or reversed ranges are fixed and reported.
    """
    steps._check_params(params, _STRUCTURED_PARAMS)
    numbered, count = numbered_paragraphs(text)
    if not count:
        raise steps.StepError("input is empty", retryable=False)
    full_prompt = f"{prompt}\n\n{KEYPOINTS_OUTPUT_INSTRUCTIONS}\n\nVersion rédigée :\n{numbered}"
    parsed, tokens = structured_call(KeyPointList, full_prompt, provider=provider, model=model, params=params,
                                     timeout=timeout)
    if not parsed.keypoints:
        raise steps.StepError("no key point in the output", **tokens)

    points, invalid = [], []
    for index, point in enumerate(parsed.keypoints, start=1):
        start, end = point.paragraph_start, point.paragraph_end
        fixed_start, fixed_end = sorted((min(max(start, 1), count), min(max(end, 1), count)))
        if (fixed_start, fixed_end) != (start, end):
            invalid.append(f"id {index}: {start}-{end} -> {fixed_start}-{fixed_end}")
        points.append({
            "id": index, "text": point.text.strip(), "importance": point.importance,
            "paragraph_start": fixed_start, "paragraph_end": fixed_end,
        })
    return {
        "output": points_yaml(points),
        **tokens,
        "cost_usd": None,
        "meta": {"keypoints": len(points), "paragraphs": count, "invalid_references": invalid},
    }


# --------------------------------------------------------------------------- #
# Steps
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class GoldStep:
    name: str
    source: str
    target: str
    func: Callable[..., dict]


GOLD_STEPS = (
    GoldStep("correction", "initial.md", "corrected.md", steps.correction),
    GoldStep("edition", "corrected.md", "edited.md", steps.edition),
    GoldStep("edited_ideas", "corrected.md", "edited_ideas.yaml", edited_ideas),
    GoldStep("summary", "edited.md", "summary.md", steps.summary),
    GoldStep("summary_keypoints", "edited.md", "summary_keypoints.yaml", summary_keypoints),
)

DEFAULT_TIMEOUT_S = 600
DEFAULT_RETRIES = 2


def dataset_files(kind: str) -> set[str]:
    """Files used by the dataset `kind` (empty for a folder outside extracts/ and full/)."""
    return set(REQUIRED_FILES.get(kind, ())) | set(OPTIONAL_FILES.get(kind, ()))


def resolve_path(value: str) -> Path:
    path = Path(value)
    if path.is_absolute() or path.exists():
        return path
    return BENCH_DIR / path


def check_config(config: dict, selected: list[GoldStep]) -> list[str]:
    problems = []
    for step in selected:
        spec = config.get(step.name)
        if not isinstance(spec, dict):
            problems.append(f"{step.name}: missing in the config")
            continue
        prompt = spec.get("prompt")
        if not prompt or not resolve_path(str(prompt)).is_file():
            problems.append(f"{step.name}: prompt file not found: {prompt}")
        model = spec.get("model")
        if not isinstance(model, dict) or not model.get("id"):
            problems.append(f"{step.name}: 'model' must be a mapping with id, provider and params")
            continue
        if str(model.get("provider", "")).lower() not in steps.PROVIDERS:
            problems.append(f"{step.name}: 'provider' must be one of {list(steps.PROVIDERS)}, got {model.get('provider')!r}")
        for key, value in (("model.params", model.get("params")), ("params", spec.get("params"))):
            if value is not None and not isinstance(value, dict):
                problems.append(f"{step.name}: '{key}' must be a mapping")
    return problems


def call_with_retries(step: GoldStep, text: str, item: LessonItem, spec: dict, timeout: float,
                      retries: int) -> tuple[dict, int]:
    """(adapter result, attempts). Raises the last error."""
    model = spec["model"]
    params = {**(model.get("params") or {}), **(spec.get("params") or {})}
    prompt = resolve_path(str(spec["prompt"])).read_text(encoding="utf-8-sig")
    for attempt in range(retries + 1):
        try:
            result = step.func(text, item=item, provider=model["provider"], model=model["id"], prompt=prompt,
                               params=dict(params), timeout=timeout)
            return result, attempt + 1
        except Exception as exc:
            if not getattr(exc, "retryable", True) or attempt == retries:
                raise
            print(f"    attempt {attempt + 1} failed ({type(exc).__name__}: {exc}), retrying")
            time.sleep(RETRY_DELAY_S * 2**attempt)
    raise AssertionError("unreachable")


def output_text(output) -> str:
    text = output if isinstance(output, str) else yaml.safe_dump(output, allow_unicode=True, sort_keys=False)
    return text if text.endswith("\n") else text + "\n"


def write_file(path: Path, text: str) -> None:
    """Write through a temporary file, so an interrupted run never leaves a partial gold file."""
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def sanity_warnings(step: GoldStep, source: str, output: str) -> list[str]:
    if step.name != "correction":
        return []
    before, _ = parse_transcript(source)
    after, problems = parse_transcript(output)
    warnings = []
    if problems:
        warnings.append(f"{len(problems)} line(s) of the output are not `- [start - end] text` lines")
    if [(s.start, s.end) for s in before] != [(s.start, s.end) for s in after]:
        warnings.append(f"segments differ from initial.md ({len(before)} -> {len(after)})")
    return warnings


def run(lesson_dir: Path, config: dict, selected: list[GoldStep], timeout: float, retries: int) -> int:
    pricing = load_pricing()
    kind = lesson_dir.parent.name
    files = dataset_files(kind)
    item = LessonItem(id=lesson_dir.name, kind=kind, path=lesson_dir)
    failed = generated = 0
    total_cost = 0.0
    for step in selected:
        source_path, target_path = lesson_dir / step.source, lesson_dir / step.target
        label = f"{step.name:17} {step.source} -> {step.target}"
        if files and step.target not in files:
            print(f"{label}: skipped, not used by the '{kind}' dataset")
            continue
        if target_path.exists():
            print(f"{label}: exists, skipped")
            continue
        if not source_path.is_file():
            print(f"{label}: SKIPPED, {step.source} not found")
            continue
        spec = config[step.name]
        model = spec["model"]
        print(f"{label}: generating with {model['id']} ({model['provider']})...")
        source = source_path.read_text(encoding="utf-8-sig")
        started = time.perf_counter()
        try:
            result, attempts = call_with_retries(step, source, item, spec, timeout, retries)
        except Exception as exc:
            failed += 1
            print(f"    FAILED: {type(exc).__name__}: {exc}")
            continue
        text = output_text(result["output"])
        write_file(target_path, text)
        generated += 1

        tokens_in, tokens_out = int(result.get("tokens_in") or 0), int(result.get("tokens_out") or 0)
        price = pricing.price(model["id"], model.get("provider"))
        cost = result.get("cost_usd")
        if cost is None and price is not None:
            cost = compute_cost(price, tokens_in, tokens_out)
        total_cost += cost or 0.0
        cost_text = f"${cost:.4f}" if cost is not None else "cost unknown (no price in configs/pricing.yaml)"
        print(f"    written: {target_path}  ({time.perf_counter() - started:.0f}s, {attempts} attempt(s), "
              f"{tokens_in:,}/{tokens_out:,} tokens, {cost_text})")
        for warning in sanity_warnings(step, source, text):
            print(f"    WARNING: {warning}")
        invalid = (result.get("meta") or {}).get("invalid_references")
        if invalid:
            print(f"    WARNING: timestamps / paragraphs not found in the input (check them): {', '.join(invalid)}")

    print(f"\n{generated} file(s) generated, {failed} failed -- cost ${total_cost:.4f}")
    if generated:
        print("Review the generated files by hand, then validate the lesson with: python -m bench.run <campaign> --check")
    return 1 if failed else 0


def main(argv: Optional[list[str]] = None) -> int:
    names = [s.name for s in GOLD_STEPS]
    parser = argparse.ArgumentParser(description="Draft the gold files of a lesson with an LLM.")
    parser.add_argument("lesson", help="lesson folder, e.g. data/extracts/Midrash.Lekh_Lekha.44-22")
    parser.add_argument("--config", required=True, help="gold config, e.g. configs/gold_v1.yaml")
    parser.add_argument("--steps", nargs="+", choices=names, help=f"subset of the steps (default: {' '.join(names)})")
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_S, help="timeout of each LLM call (s)")
    parser.add_argument("--retries", type=int, default=DEFAULT_RETRIES, help="retries of a failed step")
    parser.add_argument("--verbose", action="store_true", help="show the logs of the app code")
    args = parser.parse_args(argv)

    sys.stdout.reconfigure(line_buffering=True)
    logging.basicConfig(level=logging.INFO if args.verbose else logging.WARNING, format="%(levelname)s %(name)s: %(message)s")
    if not args.verbose:
        logging.getLogger("services").setLevel(logging.CRITICAL)

    lesson_dir = resolve_path(args.lesson)
    if not lesson_dir.is_dir():
        print(f"lesson folder not found: {args.lesson}")
        return 2
    config_path = resolve_path(args.config)
    if not config_path.is_file():
        print(f"config not found: {args.config}")
        return 2
    config = yaml.safe_load(config_path.read_text(encoding="utf-8-sig")) or {}
    print(f"Lesson: {lesson_dir}\nConfig: {config_path}\n")

    selected = [s for s in GOLD_STEPS if not args.steps or s.name in args.steps]
    files = dataset_files(lesson_dir.parent.name)
    to_run = [s for s in selected if not (lesson_dir / s.target).exists() and (not files or s.target in files)]
    problems = check_config(config, to_run)
    if problems:
        for problem in problems:
            print(f"ERROR {problem}")
        return 2
    return run(lesson_dir, config, selected, args.timeout, args.retries)


if __name__ == "__main__":
    sys.exit(main())
